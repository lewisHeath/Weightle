# Deduplicate by slug
seen = set()
unique = []
for it in items:
    sid = slug(it["name"])
    base = sid
    n = 2
    while sid in seen:
        sid = f"{base}-{n}"
        n += 1
    seen.add(sid)
    it["id"] = sid
    unique.append(it)

out = sys.argv[1] if len(sys.argv) > 1 else "src/data/catalog-seed.jsonl"
with open(out, "w") as f:
    for it in unique:
        f.write(json.dumps(it) + "\n")

print(f"Wrote {len(unique)} seed entries to {out}", file=sys.stderr)
