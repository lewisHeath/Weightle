def slug(name: str) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-")
    return s[:64] or "item"

def entry(name, mass, category, wiki=None, qualifier=None):
    return {
        "name": name,
        "massKg": round(float(mass), 6),
        "category": category,
        "wikiTitle": wiki or name.replace(" ", "_"),
        "qualifier": qualifier or f"Typical {name.lower()}",
    }

items = []

def add_many(rows):
    for row in rows:
        items.append(entry(*row))

